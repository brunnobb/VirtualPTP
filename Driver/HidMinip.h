#pragma once

#pragma warning(push)
#pragma warning(disable: 4005)
#define UMDF_USING_NTSTATUS
#include <windows.h>
#include <winioctl.h>
#include <ntstatus.h>
#pragma warning(pop)

#define HID_HID_DESCRIPTOR_TYPE         0x21
#define HID_REPORT_DESCRIPTOR_TYPE      0x22

#define HID_CTL_CODE(id) \
    CTL_CODE(FILE_DEVICE_KEYBOARD, (id), METHOD_NEITHER, FILE_ANY_ACCESS)
#define HID_BUFFER_CTL_CODE(id) \
    CTL_CODE(FILE_DEVICE_KEYBOARD, (id), METHOD_BUFFERED, FILE_ANY_ACCESS)
#define HID_IN_CTL_CODE(id) \
    CTL_CODE(FILE_DEVICE_KEYBOARD, (id), METHOD_IN_DIRECT, FILE_ANY_ACCESS)
#define HID_OUT_CTL_CODE(id) \
    CTL_CODE(FILE_DEVICE_KEYBOARD, (id), METHOD_OUT_DIRECT, FILE_ANY_ACCESS)

// Standard HID minidriver IOCTLs passed from MsHidUmdf.sys
#define IOCTL_HID_GET_DEVICE_DESCRIPTOR             HID_CTL_CODE(0)
#define IOCTL_HID_GET_REPORT_DESCRIPTOR             HID_CTL_CODE(1)
#define IOCTL_HID_READ_REPORT                       HID_CTL_CODE(2)
#define IOCTL_HID_WRITE_REPORT                      HID_CTL_CODE(3)
#define IOCTL_HID_GET_STRING                        HID_CTL_CODE(4)
#define IOCTL_HID_GET_INDEXED_STRING                HID_OUT_CTL_CODE(120)
#define IOCTL_HID_ACTIVATE_DEVICE                   HID_CTL_CODE(7)
#define IOCTL_HID_DEACTIVATE_DEVICE                 HID_CTL_CODE(8)
#define IOCTL_HID_GET_DEVICE_ATTRIBUTES             HID_CTL_CODE(9)
#define IOCTL_HID_SET_FEATURE                       HID_IN_CTL_CODE(100)
#define IOCTL_HID_GET_FEATURE                       HID_OUT_CTL_CODE(100)
#define IOCTL_HID_GET_INPUT_REPORT                  HID_OUT_CTL_CODE(104)
#define IOCTL_HID_SET_OUTPUT_REPORT                 HID_IN_CTL_CODE(105)

// UMDF 2 specific HID minidriver IOCTLs generated by MsHidUmdf.sys (METHOD_NEITHER)
#define IOCTL_UMDF_HID_SET_FEATURE                  HID_CTL_CODE(20)
#define IOCTL_UMDF_HID_GET_FEATURE                  HID_CTL_CODE(21)
#define IOCTL_UMDF_HID_SET_OUTPUT_REPORT            HID_CTL_CODE(22)
#define IOCTL_UMDF_HID_GET_INPUT_REPORT             HID_CTL_CODE(23)

#pragma pack(push, 4)
typedef struct _HID_DEVICE_ATTRIBUTES {
    ULONG           Size;
    USHORT          VendorID;
    USHORT          ProductID;
    USHORT          VersionNumber;
    USHORT          Reserved[11];
} HID_DEVICE_ATTRIBUTES, *PHID_DEVICE_ATTRIBUTES;
#pragma pack(pop)

#pragma pack(push, 1)
typedef struct _HID_DESCRIPTOR {
    UCHAR   bLength;
    UCHAR   bDescriptorType;
    USHORT  bcdHID;
    UCHAR   bCountry;
    UCHAR   bNumDescriptors;
    struct _HID_DESCRIPTOR_DESC_LIST {
       UCHAR   bReportType;
       USHORT  wReportLength;
    } DescriptorList[1];
} HID_DESCRIPTOR, *PHID_DESCRIPTOR;
#pragma pack(pop)

typedef struct _HID_XFER_PACKET {
    PUCHAR  reportBuffer;
    ULONG   reportBufferLen;
    UCHAR   reportId;
} HID_XFER_PACKET, *PHID_XFER_PACKET;
